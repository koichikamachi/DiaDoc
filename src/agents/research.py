"""Analyst Radar（調査）。事実と論点を示す。意見は言わない。"""

from __future__ import annotations

from agents.base import Agent


class Radar(Agent):
    id = "radar"
    name = "Analyst Radar"

    def role_prompt(self, phase):
        return """役割：Analyst Radar（調査担当）。
- 資料から、論争の土台になる事実と数字だけを示す。改善案や賛否は述べない（action は「提示」）。
- 第1ラウンドでは、争うべき論点を最大3件まで agenda_ops に登録する（op=open、id は A1〜A3、title は20字以内）。
- 本文では「論点を開きます」「論点を設定します」のような手続きの言い方をしない。調査担当として、
  「〜という論点があることを指摘します」「〜に注意を向けるべきです」のように、事実から気づいた点を指摘する言い方にする。
- 第2ラウンド以降は、前のラウンドで何が通り、資金の監視指標がどう動いたかを数字で示す。
- 資料に書かれていないが決着に必要なデータがあれば、それを名指しする（データ請求）。
- 資金の監視指標に「約定返済：BS記載に疑問あり、確認が必要」とあるときは、必須の宿題として
  「借入金返済予定表（金銭消費貸借契約書）」の提出を求め、資金不足の有無が判定保留であること
  （返済を0とみなした数字でトリアージ不要と言い切れないこと）を、参考試算の数字とともに必ず指摘する。"""

    def task(self, state, ctx):
        if state.round == 1:
            return ("第1ラウンドの冒頭です。事実と数字を示し、争うべき論点を最大3件、agenda_ops に登録してください。"
                    "本文では、論点を「開く」のではなく、注意を向けるべき点として指摘してください。")
        return "前のラウンドの結果と、資金の監視指標の動き、改善レバーの消化状況を数字で示してください。"
